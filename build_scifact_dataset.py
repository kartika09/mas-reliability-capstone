def load_dataset(path="mas_scifact_dataset.json"):
    """Load the single dataset file. Adds data['passages'] = {passage_id: passage} for quick lookup."""
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    data["passages"] = {p["passage_id"]: p for p in data["corpus"]}
    return data


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-dir", help="folder that already contains SciFact's corpus.jsonl and claims_*.jsonl")
    parser.add_argument("--out", default="mas_scifact_dataset.json")
    parser.add_argument("--n-support", type=int, default=70)
    parser.add_argument("--n-contradict", type=int, default=70)
    parser.add_argument("--n-noinfo", type=int, default=60)
    parser.add_argument("--dev-fraction", type=float, default=0.2, help="share of each label kept as the tune split")
    parser.add_argument("--seed", type=int, default=42)
    # parse_known_args ignores extra flags, so this also works if pasted into a Colab/Jupyter cell
    args, _ = parser.parse_known_args()

    data_dir = Path(args.data_dir) if args.data_dir else download_scifact("scifact_raw")

    # 1. Corpus: one passage per abstract (we keep every abstract)
    corpus = []
    for doc in read_jsonl(data_dir / "corpus.jsonl"):
        corpus.append({
            "passage_id": f"D{doc['doc_id']}",
            "title": doc["title"],
            "sentences": doc["abstract"],
            "text": doc["title"] + ". " + " ".join(doc["abstract"]),
        })

    # 2. Questions: only labeled claims (train + dev), grouped by gold label
    by_label = {"SUPPORT": [], "CONTRADICT": [], "NOINFO": []}
    n_skipped_mixed = 0
    for name, scifact_split in (("claims_train.jsonl", "train"), ("claims_dev.jsonl", "dev")):
        for claim in read_jsonl(data_dir / name):
            label = claim_label(claim)
            if label is None:
                n_skipped_mixed += 1
            else:
                by_label[label].append(build_question(claim, label, scifact_split))

    wanted = {"SUPPORT": args.n_support, "CONTRADICT": args.n_contradict, "NOINFO": args.n_noinfo}
    rng = random.Random(args.seed)          # fixed seed, so everyone gets the same sample
    questions = []
    for label, pool in by_label.items():
        rng.shuffle(pool)
        chosen = pool[: wanted[label]]
        n_tune = round(len(chosen) * args.dev_fraction)
        for i, q in enumerate(chosen):
            q["split"] = "tune" if i < n_tune else "eval"
            questions.append(q)
    rng.shuffle(questions)

    # 3. Write ONE file
    dataset = {
        "info": make_info(args, len(corpus), questions, n_skipped_mixed),
        "questions": questions,
        "corpus": corpus,
    }
    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(dataset, f, ensure_ascii=False)

    print(f"\nWrote {args.out}")
    print(f"  abstracts in corpus: {len(corpus)}")
    print(f"  questions:           {len(questions)}")
    print("  by label/split:     ", dataset["info"]["counts"]["by_label_and_split"])


if __name__ == "__main__":
    main()

