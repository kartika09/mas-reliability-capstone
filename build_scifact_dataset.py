"""
Build ONE dataset file for the MAS reliability project from SciFact.

SciFact (Wadden et al., 2020, licensed CC BY 4.0) has scientific claims and a
corpus of paper abstracts. Every claim has a gold label:
    SUPPORT     - an abstract supports the claim
    CONTRADICT  - an abstract refutes the claim
    NOINFO      - no abstract in the corpus settles it

The output is a single file, mas_scifact_dataset.json, with three parts:
    "info"       everything ABOUT the data: source, license, what we changed,
                 label meanings, schema, counts, how to score, limitations
    "questions"  the sampled claims with gold labels and gold evidence
    "corpus"     every abstract (the agents retrieve from these)

Run it:
    python build_scifact_dataset.py                        # downloads SciFact first
    python build_scifact_dataset.py --data-dir some/dir    # if you already have it

Use it from other code:
    from build_scifact_dataset import load_dataset
    data = load_dataset("mas_scifact_dataset.json")
    data["questions"], data["corpus"], data["passages"]["D123"]

SciFact's own test claims have no public labels, so we only use its train and
dev claims (which do).
"""

import argparse
import json
import random
import tarfile
import urllib.request
from collections import Counter
from datetime import date
from pathlib import Path

URL = "https://scifact.s3-us-west-2.amazonaws.com/release/latest/data.tar.gz"


def read_jsonl(path):
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def download_scifact(dest):
    """Download and unpack the official SciFact tarball, return the folder that holds corpus.jsonl."""
    dest = Path(dest)
    dest.mkdir(parents=True, exist_ok=True)
    tar_path = dest / "scifact_data.tar.gz"
    print("Downloading SciFact ...")
    urllib.request.urlretrieve(URL, tar_path)
    with tarfile.open(tar_path) as tar:
        try:
            tar.extractall(dest, filter="data")   # safer extraction on newer Python
        except TypeError:
            tar.extractall(dest)                  # older Python has no 'filter' option
    return next(dest.rglob("corpus.jsonl")).parent


def claim_label(claim):
    """SUPPORT / CONTRADICT / NOINFO for one claim. Returns None if the labels are mixed."""
    labels = {r["label"] for rationales in claim["evidence"].values() for r in rationales}
    if not labels:
        return "NOINFO"
    if len(labels) == 1:
        return labels.pop()
    return None  # mixed labels: ambiguous, we skip these claims


def build_question(claim, label, scifact_split):
    gold_sentences = {}
    for doc_id, rationales in claim["evidence"].items():
        idx = sorted({i for r in rationales for i in r["sentences"]})
        gold_sentences[f"D{doc_id}"] = idx
    return {
        "qid": f"Q{claim['id']}",
        "claim": claim["claim"],
        "gold_label": label,
        "gold_passages": list(gold_sentences.keys()),   # empty for NOINFO
        "gold_sentences": gold_sentences,               # which sentences hold the evidence
        "cited_passages": [f"D{d}" for d in claim.get("cited_doc_ids", [])],
        "scifact_split": scifact_split,                 # where the claim came from in SciFact
    }


